#!/usr/bin/env python3
"""Rebuild or verify afterglow/cache.appcache.

The console's HTML5 Application Cache only refetches when the manifest itself
changes. afterglow lists each file with a content hash so any edit changes the
manifest. This is the same format as afterglow's make-manifest.sh, implemented
in Python so it also runs on Windows.

Usage:
    py tools/manifest.py --check
    py tools/manifest.py --write
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AFTERGLOW = ROOT / "afterglow"
MANIFEST = AFTERGLOW / "cache.appcache"

FILES = [
    "index.html",
    "jb.html",
    "style.css",
    "launch.js",
    "meme.png",
    "jb.js",
    "core.js",
    "mem.js",
    "int64.js",
    "ps4_offsets.js",
    "afterglow.js",
    "patchset-1200.bin",
    "patchset-1202.bin",
    "patchset-1250.bin",
    "patchset-1252.bin",
    "patchset-1300.bin",
    "patchset-1302.bin",
    "patchset-1304.bin",
    "patchset-1350.bin",
    "patchset-1352.bin",
    "patchset-1400.bin",
    "patchset-1402.bin",
    "hen.bin",
    "goldhen.bin",
]


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:32]


def build() -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "CACHE MANIFEST",
        "# generated by tools/manifest.py -- do not edit by hand",
        f"# {stamp}",
        "",
    ]

    for name in FILES:
        path = AFTERGLOW / name
        if not path.is_file():
            raise SystemExit(f"missing: {path}")
        lines.append(f"{name} #{digest(path)}")

    lines += [
        "",
        "FALLBACK:",
        "jb.html jb.html",
        "",
        "NETWORK:",
        "*",
        "",
    ]

    return "\n".join(lines)


def verify() -> int:
    if not MANIFEST.is_file():
        print(f"missing: {MANIFEST}")
        return 1

    entries = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        parts = line.strip().split()
        if len(parts) == 2 and parts[1].startswith("#") and len(parts[1]) == 33:
            entries[parts[0]] = parts[1][1:]

    failures = 0
    for name in FILES:
        path = AFTERGLOW / name
        if not path.is_file():
            print(f"MISSING {name}")
            failures += 1
            continue
        if name not in entries:
            print(f"NOT LISTED {name}")
            failures += 1
            continue
        got = digest(path)
        if got != entries[name]:
            print(f"MISMATCH {name} manifest={entries[name]} file={got}")
            failures += 1

    if failures:
        print(f"{failures} manifest check(s) failed; run --write")
        return 1

    print(f"manifest OK: {len(FILES)} entries")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Afterglow cache manifest tool")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="verify the manifest (default)")
    group.add_argument("--write", action="store_true", help="rewrite the manifest")
    args = parser.parse_args()

    if args.write:
        text = build()
        with MANIFEST.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print(f"wrote {MANIFEST} ({len(FILES)} entries)")
        return 0

    return verify()


if __name__ == "__main__":
    raise SystemExit(main())
